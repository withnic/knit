// copyDir copies the directory tree src into dst.
func copyDir(t *testing.T, src, dst string) {
	t.Helper()
	err := filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o750)
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, data, 0o600)
	})
	if err != nil {
		t.Fatalf("copying %s: %v", src, err)
	}
}

func goCmd(t *testing.T, dir string, args ...string) {
	t.Helper()
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod", "GOPROXY=off")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("go %s: %v\n%s", strings.Join(args, " "), err, out)
	}
}

// TestGen_EndToEnd generates code into a temporary copy of the fixture module,
// then builds, vets and runs it: the LIFO cleanup behavior is verified by
// executing testdata/fixture/gen/lifo/lifo_test.go against the generated code.
func TestGen_EndToEnd(t *testing.T) {
	if testing.Short() {
		t.Skip("spawns go build / go test")
	}
	root := t.TempDir()
	copyDir(t, filepath.Join("testdata", "fixture"), filepath.Join(root, "fixture"))
	copyDir(t, filepath.Join("testdata", "wire"), filepath.Join(root, "wire"))
	dir := filepath.Join(root, "fixture")
	t.Setenv("GOWORK", "off")
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Setenv("GOPROXY", "off")

	opts := GenOptions{
		Mode:     WireMode,
		Dir:      dir,
		Patterns: []string{"./basic", "./samename/...", "./gen/..."},
		Now:      func() time.Time { return time.Unix(0, 0).UTC() },
	}
	res, err := Gen(context.Background(), opts)
	if err != nil {
		t.Fatalf("Gen() error = %v", err)
	}
	var rels []string
	for _, f := range res.Files {
		rel, _ := filepath.Rel(dir, f.Path)
		rels = append(rels, filepath.ToSlash(rel))
	}
	wantFiles := []string{"basic/wire_gen.go", "gen/alias/wire_gen.go", "gen/collide/app/wire_gen.go", "gen/lifo/wire_gen.go", "gen/shadow/wire_gen.go", "samename/di/wire_gen.go"}
	if strings.Join(rels, ",") != strings.Join(wantFiles, ",") {
		t.Fatalf("generated files = %v, want %v", rels, wantFiles)
	}

	graphPath := filepath.Join(dir, graphschema.DefaultPath)
	if err := res.Write(graphPath); err != nil {
		t.Fatalf("Write() error = %v", err)
	}
	g, err := graphschema.ReadFile(graphPath)
	if err != nil {
		t.Fatalf("reading written graph: %v", err)
	}
	if len(g.Injectors) != 7 {
		t.Errorf("graph has %d injectors, want 7", len(g.Injectors))
	}

	// Regenerating with the generated files in place is byte-identical.
	again, err := Gen(context.Background(), opts)
	if err != nil {
		t.Fatalf("second Gen() error = %v", err)
	}
	for i := range res.Files {
		if !bytes.Equal(res.Files[i].Content, again.Files[i].Content) {
			t.Errorf("%s differs between runs", rels[i])
		}
	}

	goCmd(t, dir, "build", "./...")
	goCmd(t, dir, "vet", "./basic", "./samename/...", "./gen/...")
	goCmd(t, dir, "test", "-count=1", "./gen/lifo")
}

func TestGen_Errors(t *testing.T) {
	if testing.Short() {
		t.Skip("spawns go list")
	}
	dir, _ := filepath.Abs(filepath.Join("testdata", "fixture"))
	t.Setenv("GOWORK", "off")
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Setenv("GOPROXY", "off")
	tests := []struct {
		name string
		opts GenOptions
		want []string
	}{
		{
			name: "all resolve errors are reported",
			opts: GenOptions{Mode: WireMode, Dir: dir, Patterns: []string{"./cycle", "./missing/..."}},
			want: []string{"injector 'InitializeA'", "circular dependency", "injector 'InitializeUserService'", "provider not found"},
		},
		{
			name: "no injectors",
			opts: GenOptions{Mode: WireMode, Dir: dir, Patterns: []string{"./missing/db"}},
			want: []string{"no injectors found"},
		},
		{
			name: "invalid output file",
			opts: GenOptions{Mode: WireMode, Dir: dir, OutFile: "sub/wire_gen.go"},
			want: []string{"must be a plain .go file name"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := Gen(context.Background(), tt.opts)
			if err == nil {
				t.Fatal("Gen() error = nil")
			}
			for _, w := range tt.want {
				if !strings.Contains(err.Error(), w) {
					t.Errorf("Gen() error lacks %q:\n%v", w, err)
				}
			}
		})
	}
}

// TestGen_ExistingOutputFiles covers files already at the output path and
// generated files left in packages without injectors.
func TestGen_ExistingOutputFiles(t *testing.T) {
	if testing.Short() {
		t.Skip("spawns go list")
	}
	const generated = "// Code generated by %s. DO NOT EDIT.\n\n//go:build !wireinject\n\npackage p\n"
	tests := []struct {
		name    string
		file    string
		content string
		pattern string
		wantErr error
	}{
		{name: "hand-written output is kept", file: "gen/lifo/wire_gen.go", content: "package lifo\n\nfunc Keep() {}\n", pattern: "./gen/lifo", wantErr: ErrNotGenerated},
		{name: "knit output is replaced", file: "gen/lifo/wire_gen.go", content: strings.Replace(generated, "%s", "knit", 1), pattern: "./gen/lifo"},
		{name: "wire output is replaced", file: "gen/lifo/wire_gen.go", content: strings.Replace(generated, "%s", "Wire", 1), pattern: "./gen/lifo"},
		{name: "stale output is reported", file: "missing/db/wire_gen.go", content: strings.Replace(generated, "%s", "knit", 1), pattern: "./missing/db", wantErr: ErrStaleGenerated},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			copyDir(t, filepath.Join("testdata", "fixture"), filepath.Join(root, "fixture"))
			copyDir(t, filepath.Join("testdata", "wire"), filepath.Join(root, "wire"))
			dir := filepath.Join(root, "fixture")
			path := filepath.Join(dir, filepath.FromSlash(tt.file))
			if err := os.WriteFile(path, []byte(tt.content), 0o600); err != nil {
				t.Fatal(err)
			}
			t.Setenv("GOWORK", "off")
			t.Setenv("GOFLAGS", "-mod=mod")
			t.Setenv("GOPROXY", "off")
			_, err := Gen(context.Background(), GenOptions{Mode: WireMode, Dir: dir, Patterns: []string{tt.pattern}})
			if !errors.Is(err, tt.wantErr) {
				t.Fatalf("Gen() error = %v, want %v", err, tt.wantErr)
			}
			if err != nil && !strings.Contains(err.Error(), path) {
				t.Errorf("Gen() error does not name %s: %v", path, err)
			}
		})
	}
}

// knitStubModule writes the marker package github.com/withnic/knit into
// dir/knit from the repository's real knit.go, so the fixture always
// exercises the published marker API.
func knitStubModule(t *testing.T, dir string) {
	t.Helper()
	src, err := os.ReadFile(filepath.Join("..", "..", "knit.go"))
	if err != nil {
		t.Fatal(err)
	}
	stub := filepath.Join(dir, "knit")
	if err := os.MkdirAll(stub, 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(stub, "go.mod"), []byte("module github.com/withnic/knit\n\ngo 1.26\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(stub, "knit.go"), src, 0o600); err != nil {
		t.Fatal(err)
	}
}

// TestGen_KnitMode generates code for the knit-mode fixture with the default
// mode and runs it: knit.Build / knit.NewSet / knit.Bind are understood,
// injector files are guarded by knitinject and the output is knit_gen.go.
func TestGen_KnitMode(t *testing.T) {
	if testing.Short() {
		t.Skip("spawns go build / go test")
	}
	root := t.TempDir()
	copyDir(t, filepath.Join("testdata", "knitfixture"), filepath.Join(root, "knitfixture"))
	knitStubModule(t, root)
	dir := filepath.Join(root, "knitfixture")
	t.Setenv("GOWORK", "off")
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Setenv("GOPROXY", "off")

	res, err := Gen(context.Background(), GenOptions{Dir: dir})
	if err != nil {
		t.Fatalf("Gen() error = %v", err)
	}
	if len(res.Files) != 1 || res.Files[0].Path != filepath.Join(dir, "app", "knit_gen.go") {
		t.Fatalf("generated files = %+v, want app/knit_gen.go", res.Files)
	}
	src := string(res.Files[0].Content)
	for _, want := range []string{"// Code generated by knit. DO NOT EDIT.\n\n//go:build !knitinject\n", "// Injectors from knit.go:"} {
		if !strings.Contains(src, want) {
			t.Errorf("generated code lacks %q:\n%s", want, src)
		}
	}
	if strings.Contains(src, "withnic/knit\"") {
		t.Errorf("generated code imports the marker package:\n%s", src)
	}
	var deps []string
	for _, d := range res.Graph.Injectors[0].Dependencies {
		deps = append(deps, strings.TrimSpace(d.Type+" "+d.BoundFrom))
	}
	wantDeps := []string{
		"*example.com/knitfixture/app.SQLStore",
		"*example.com/knitfixture/app.Server",
		"example.com/knitfixture/app.DSN",
		"example.com/knitfixture/app.Store *example.com/knitfixture/app.SQLStore",
	}
	if strings.Join(deps, ",") != strings.Join(wantDeps, ",") {
		t.Errorf("graph dependencies = %v, want %v", deps, wantDeps)
	}
	if err := res.Write(""); err != nil {
		t.Fatal(err)
	}
	goCmd(t, dir, "vet", "./...")
	goCmd(t, dir, "test", "-count=1", "./...")

	// The wire mode does not see knit injectors.
	if _, err := Gen(context.Background(), GenOptions{Mode: WireMode, Dir: dir}); err == nil ||
		!strings.Contains(err.Error(), "no injectors found") || !strings.Contains(err.Error(), "-mode=knit") {
		t.Errorf("Gen(WireMode) on a knit project: error = %v, want no injectors with a -mode=knit hint", err)
	}
}

