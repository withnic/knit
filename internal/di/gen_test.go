func TestParseMode(t *testing.T) {
	for _, m := range Modes {
		if got, err := ParseMode(m.Name); err != nil || got != m {
			t.Errorf("ParseMode(%q) = %+v, %v", m.Name, got, err)
		}
	}
	if _, err := ParseMode("dagger"); err == nil || !strings.Contains(err.Error(), "knit, wire") {
		t.Errorf("ParseMode(dagger) error = %v", err)
	}
	if (Mode{}).orDefault() != KnitMode {
		t.Error("zero Mode does not default to KnitMode")
	}
}
